// Generate the Institute's server-only quiz answer keys + the answer-free
// question files the browser gets. Runs in `npm run build` (so the keys can
// never drift from the committed lesson data) and standalone.
//
//   functions/api/_institute-quiz-keys.js   { "<lesson-id>": [answerIdx...],
//                                             "<track-id>":  [answerIdx...] }   (server only)
//   web/src/data/institute/exam/<track>.json { questions: [{ q, options }] }    (no answers)
//   web/public/data/institute/lessons/**     written by sync-institute.mjs with
//                                             quiz[].answer / .explanation stripped
//
// Same discipline as the main site's scripts/build_quiz_keys.py: the keys live
// only in the Worker bundle; the browser never sees an answer, so a learner
// can't forge a passing score / certificate.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const IMPORTED = 'src/data/institute/imported';
const KEYS_OUT = '../functions/api/_institute-quiz-keys.js';
const EXAM_OUT = 'src/data/institute/exam';

if (!existsSync(IMPORTED)) {
  writeFileSync(KEYS_OUT, '// AUTO-GENERATED by web/scripts/build-institute-quiz-keys.mjs — do not edit.\nexport const INSTITUTE_QUIZ_KEYS = {};\n');
  console.log('build-institute-quiz-keys: no imported lessons yet — wrote empty keys');
  process.exit(0);
}

const keys = {};
const exams = {};
mkdirSync(EXAM_OUT, { recursive: true });

for (const track of readdirSync(IMPORTED, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
  const tDir = join(IMPORTED, track);
  const idx = JSON.parse(readFileSync(join(tDir, 'index.json'), 'utf-8'));
  const pool = [];

  for (const lref of idx.lessons) {
    const lesson = JSON.parse(readFileSync(join(tDir, `${lref.slug}.json`), 'utf-8'));
    const quiz = lesson.quiz || [];
    if (quiz.length) {
      keys[lesson.id] = quiz.map((q) => q.answer);
      for (const q of quiz) pool.push({ q: q.q, options: q.options, answer: q.answer });
    }
  }

  if (pool.length) {
    keys[track] = pool.map((q) => q.answer);
    exams[track] = { track, count: pool.length, questions: pool.map((q) => ({ q: q.q, options: q.options })) };
    writeFileSync(join(EXAM_OUT, `${track}.json`), JSON.stringify(exams[track], null, 2) + '\n');
  }
}

const body =
  '// AUTO-GENERATED by web/scripts/build-institute-quiz-keys.mjs — do not edit by hand.\n' +
  '// Server-only answer keys for Institute of Technology quizzes + phase exams.\n' +
  '// { "<lesson-id>": [correctOptionIndex,...], "<track-id>": [pool answers,...] }\n' +
  'export const INSTITUTE_QUIZ_KEYS = ' + JSON.stringify(keys) + ';\n';
writeFileSync(KEYS_OUT, body);

const nLesson = Object.keys(keys).filter((k) => k.includes('::')).length;
const nTrack = Object.keys(keys).filter((k) => !k.includes('::')).length;
console.log(`build-institute-quiz-keys: ${nLesson} lesson keys, ${nTrack} phase-exam pools, ${Object.keys(exams).length} exam files`);
